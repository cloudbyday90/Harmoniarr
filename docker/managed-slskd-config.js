import { chmod, mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';

const defaultConfigPath = '/app/slskd.yml';
const defaultSecretDirectory = '/run/secrets';
const defaultListenPort = 50300;
const defaultApiKeyCidr = '0.0.0.0/0,::/0';

const requiredSecretNames = [
  'slskd_api_key',
  'slskd_soulseek_username',
  'slskd_soulseek_password',
  'slskd_web_username',
  'slskd_web_password',
  'slskd_jwt_key',
];

function formatYamlString(value) {
  return JSON.stringify(value);
}

function containsControlCharacters(value) {
  return [...value].some((character) => {
    const codePoint = character.codePointAt(0);
    return codePoint <= 0x1f || codePoint === 0x7f;
  });
}

function normalizeSecretValue(value, name) {
  if (typeof value !== 'string') {
    throw new Error(`${name} must be a string`);
  }

  const normalized = value.replace(/\r?\n$/u, '');

  if (!normalized) {
    throw new Error(`${name} must not be empty`);
  }

  if (containsControlCharacters(normalized)) {
    throw new Error(`${name} must not contain control characters`);
  }

  return normalized;
}

function normalizeAbsolutePath(value, name) {
  if (typeof value !== 'string' || !isAbsolute(value)) {
    throw new Error(`${name} must be an absolute path`);
  }

  return value;
}

function normalizeListenPort(value) {
  const parsed = Number.parseInt(String(value), 10);
  if (!Number.isInteger(parsed) || parsed < 1 || parsed > 65535) {
    throw new Error('HARMONIARR_SLSKD_LISTEN_PORT must be an integer between 1 and 65535');
  }

  return parsed;
}

function normalizeApiKey(value) {
  if (value.length < 16 || value.length > 255) {
    throw new Error('slskd_api_key must contain between 16 and 255 characters');
  }

  return value;
}

function requireMinimumLength(value, name, minimumLength) {
  if (value.length < minimumLength) {
    throw new Error(`${name} must contain at least ${minimumLength} characters`);
  }

  return value;
}

export function renderManagedSlskdConfig({
  apiKey,
  apiKeyCidr = defaultApiKeyCidr,
  downloadsDirectory = '/data/downloads',
  incompleteDirectory = '/data/incomplete',
  jwtKey,
  listenPort = defaultListenPort,
  soulseekPassword,
  soulseekUsername,
  webPassword,
  webUsername,
} = {}) {
  const normalizedApiKey = normalizeApiKey(normalizeSecretValue(apiKey ?? '', 'slskd_api_key'));
  const normalizedJwtKey = requireMinimumLength(
    normalizeSecretValue(jwtKey ?? '', 'slskd_jwt_key'),
    'slskd_jwt_key',
    16,
  );
  const normalizedSoulseekUsername = normalizeSecretValue(soulseekUsername ?? '', 'slskd_soulseek_username');
  const normalizedSoulseekPassword = normalizeSecretValue(soulseekPassword ?? '', 'slskd_soulseek_password');
  const normalizedWebUsername = normalizeSecretValue(webUsername ?? '', 'slskd_web_username');
  const normalizedWebPassword = normalizeSecretValue(webPassword ?? '', 'slskd_web_password');
  const normalizedDownloadsDirectory = normalizeAbsolutePath(downloadsDirectory, 'HARMONIARR_SLSKD_DOWNLOADS_DIRECTORY');
  const normalizedIncompleteDirectory = normalizeAbsolutePath(incompleteDirectory, 'HARMONIARR_SLSKD_INCOMPLETE_DIRECTORY');
  const normalizedApiKeyCidr = normalizeSecretValue(apiKeyCidr, 'HARMONIARR_SLSKD_API_KEY_CIDR');
  const normalizedListenPort = normalizeListenPort(listenPort);

  return `# Generated by Harmoniarr's managed slskd deployment. Do not edit manually.\n# Update the deployment secrets or managed configuration inputs, then rerun slskd-config.\nheadless: true\nremote_configuration: false\nremote_file_management: false\ndirectories:\n  incomplete: ${formatYamlString(normalizedIncompleteDirectory)}\n  downloads: ${formatYamlString(normalizedDownloadsDirectory)}\nweb:\n  port: 5030\n  ip_address: ${formatYamlString('0.0.0.0,[::]')}\n  logging: false\n  https:\n    disabled: true\n  authentication:\n    disabled: false\n    username: ${formatYamlString(normalizedWebUsername)}\n    password: ${formatYamlString(normalizedWebPassword)}\n    jwt:\n      key: ${formatYamlString(normalizedJwtKey)}\n      ttl: 604800000\n    api_keys:\n      harmoniarr:\n        key: ${formatYamlString(normalizedApiKey)}\n        role: readwrite\n        cidr: ${formatYamlString(normalizedApiKeyCidr)}\nsoulseek:\n  username: ${formatYamlString(normalizedSoulseekUsername)}\n  password: ${formatYamlString(normalizedSoulseekPassword)}\n  listen_ip_address: ${formatYamlString('0.0.0.0')}\n  listen_port: ${normalizedListenPort}\n`;
}

export async function readManagedSlskdSecrets({
  readFileFn = readFile,
  secretDirectory = defaultSecretDirectory,
} = {}) {
  const normalizedSecretDirectory = normalizeAbsolutePath(secretDirectory, 'HARMONIARR_SLSKD_SECRET_DIRECTORY');
  const entries = await Promise.all(requiredSecretNames.map(async (name) => {
    const rawValue = await readFileFn(`${normalizedSecretDirectory}/${name}`, 'utf8');
    return [name, normalizeSecretValue(rawValue, name)];
  }));

  return Object.fromEntries(entries);
}

export async function writeManagedSlskdConfig({
  chmodFn = chmod,
  configPath = defaultConfigPath,
  content,
  mkdirFn = mkdir,
  renameFn = rename,
  writeFileFn = writeFile,
} = {}) {
  const normalizedConfigPath = normalizeAbsolutePath(configPath, 'HARMONIARR_SLSKD_CONFIG_PATH');
  if (typeof content !== 'string' || !content) {
    throw new Error('content is required');
  }

  const configDirectory = dirname(normalizedConfigPath);
  const temporaryPath = `${normalizedConfigPath}.tmp-${globalThis.process.pid}`;

  await mkdirFn(configDirectory, { mode: 0o700, recursive: true });
  await writeFileFn(temporaryPath, content, { encoding: 'utf8', flag: 'w', mode: 0o600 });
  await chmodFn(temporaryPath, 0o600);
  await renameFn(temporaryPath, normalizedConfigPath);
  await chmodFn(normalizedConfigPath, 0o600);

  return normalizedConfigPath;
}

export async function configureManagedSlskd({
  env = globalThis.process.env,
  readManagedSecretsFn = readManagedSlskdSecrets,
  writeConfigFn = writeManagedSlskdConfig,
} = {}) {
  const secrets = await readManagedSecretsFn({
    secretDirectory: env.HARMONIARR_SLSKD_SECRET_DIRECTORY ?? defaultSecretDirectory,
  });
  const content = renderManagedSlskdConfig({
    apiKey: secrets.slskd_api_key,
    apiKeyCidr: env.HARMONIARR_SLSKD_API_KEY_CIDR ?? defaultApiKeyCidr,
    downloadsDirectory: env.HARMONIARR_SLSKD_DOWNLOADS_DIRECTORY ?? '/data/downloads',
    incompleteDirectory: env.HARMONIARR_SLSKD_INCOMPLETE_DIRECTORY ?? '/data/incomplete',
    jwtKey: secrets.slskd_jwt_key,
    listenPort: env.HARMONIARR_SLSKD_LISTEN_PORT ?? defaultListenPort,
    soulseekPassword: secrets.slskd_soulseek_password,
    soulseekUsername: secrets.slskd_soulseek_username,
    webPassword: secrets.slskd_web_password,
    webUsername: secrets.slskd_web_username,
  });

  const configPath = await writeConfigFn({
    configPath: env.HARMONIARR_SLSKD_CONFIG_PATH ?? defaultConfigPath,
    content,
  });

  return { configPath };
}

async function main() {
  const { configPath } = await configureManagedSlskd();
  globalThis.process.stdout.write(`[harmoniarr-managed-slskd-config] wrote ${configPath}\n`);
}

if (globalThis.process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    globalThis.process.stderr.write(`[harmoniarr-managed-slskd-config] ${error instanceof Error ? error.message : String(error)}\n`);
    globalThis.process.exitCode = 1;
  });
}
